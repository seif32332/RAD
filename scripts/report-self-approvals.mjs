#!/usr/bin/env node
/**
 * READ-ONLY audit report (DEC-001/002/008, risk R-005): historical payment requests where the same
 * user created the request AND approved it (owner portal) and/or recorded it as paid.
 *
 *   node scripts/report-self-approvals.mjs                         > self-approvals.csv
 *   node scripts/report-self-approvals.mjs --env-file /etc/radeef/<tenant>.env --since 2025-01-01
 *   node scripts/report-self-approvals.mjs --all                   # every request with a known maker
 *
 * Options:
 *   --env-file <path>   load environment variables from this file (default: ./.env when present)
 *   --since <date>      only requests created on/after this date (YYYY-MM-DD)
 *   --all               list every request whose maker is known, not only self-approved/self-paid ones
 *
 * Sources, per PaymentRequest (nothing is written to the database):
 *   maker    : PaymentRequest.requestedById, else the AuditLog CREATE row of the PaymentRequest,
 *              else the AuditLog CREATE row of a RenewalArchive whose details.paymentRequestId is it.
 *   approver : PaymentRequest.approvedById, else the latest AuditLog APPROVE row of the PaymentRequest.
 *   payer    : PaymentRequest.paidById, else the latest AuditLog UPDATE row whose details.status = PAID.
 *   override : AuditLog SELF_APPROVAL_OVERRIDE rows (self-approvals that the new rule allowed and logged).
 * Requests generated by the system (visa fees, settlement payouts, leave visas) have no maker in the
 * log and are not reported (maker unknown).
 *
 * Output: CSV on stdout (UTF-8, RFC 4180 quoting); a summary line on stderr.
 */
import { existsSync } from 'node:fs';
import { PrismaClient } from '@prisma/client';

function parseArgs(argv) {
  const out = { envFile: null, since: null, all: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--env-file') out.envFile = argv[++i];
    else if (a === '--since') out.since = argv[++i];
    else if (a === '--all') out.all = true;
    else if (a === '-h' || a === '--help') {
      console.error('Usage: node scripts/report-self-approvals.mjs [--env-file <path>] [--since YYYY-MM-DD] [--all]');
      process.exit(0);
    } else {
      console.error(`Unknown argument: ${a}`);
      process.exit(2);
    }
  }
  if (out.envFile === undefined || out.since === undefined) {
    console.error('Missing value for --env-file / --since');
    process.exit(2);
  }
  if (out.since && !/^\d{4}-\d{2}-\d{2}$/.test(out.since)) {
    console.error('--since must be YYYY-MM-DD');
    process.exit(2);
  }
  return out;
}

function loadEnv(file) {
  const p = file ?? (existsSync('.env') ? '.env' : null);
  if (!p) return;
  if (!existsSync(p)) throw new Error(`env file not found: ${p}`);
  if (typeof process.loadEnvFile !== 'function') throw new Error('Node >= 20.12 is required for --env-file');
  process.loadEnvFile(p);
}

function parseDetails(raw) {
  if (!raw) return null;
  try {
    const v = JSON.parse(raw);
    return v && typeof v === 'object' ? v : null;
  } catch {
    return null;
  }
}

function csvCell(v) {
  if (v === null || v === undefined) return '';
  const s = v instanceof Date ? v.toISOString() : String(v);
  return /[",\r\n]/.test(s) || /^[=+\-@]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  loadEnv(args.envFile);
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is not set (export it, put it in .env or pass --env-file)');

  const prisma = new PrismaClient();
  try {
    const where = args.since ? { createdAt: { gte: new Date(`${args.since}T00:00:00Z`) } } : {};
    const payments = await prisma.paymentRequest.findMany({
      where,
      orderBy: { createdAt: 'asc' },
      select: {
        id: true, title: true, amount: true, status: true, entityType: true, createdAt: true,
        requestedById: true, approvedById: true, paidById: true,
      },
    });
    const ids = payments.map((p) => p.id);

    const logs = ids.length
      ? await prisma.auditLog.findMany({
          where: { entityType: 'PaymentRequest', entityId: { in: ids } },
          orderBy: { createdAt: 'asc' },
          select: { userId: true, action: true, entityId: true, details: true, createdAt: true },
        })
      : [];
    // Renewal payment requests are logged on the RenewalArchive row (details.paymentRequestId).
    const renewalLogs = await prisma.auditLog.findMany({
      where: { entityType: 'RenewalArchive', action: 'CREATE', details: { contains: 'paymentRequestId' } },
      select: { userId: true, details: true, createdAt: true },
    });

    const makerFromLog = new Map();
    const approverFromLog = new Map();
    const payerFromLog = new Map();
    const overrides = new Map();
    for (const l of logs) {
      if (!l.userId || !l.entityId) continue;
      if (l.action === 'CREATE' && !makerFromLog.has(l.entityId)) makerFromLog.set(l.entityId, { userId: l.userId, at: l.createdAt });
      else if (l.action === 'APPROVE') approverFromLog.set(l.entityId, { userId: l.userId, at: l.createdAt });
      else if (l.action === 'UPDATE' && parseDetails(l.details)?.status === 'PAID') payerFromLog.set(l.entityId, { userId: l.userId, at: l.createdAt });
      else if (l.action === 'SELF_APPROVAL_OVERRIDE') {
        const d = parseDetails(l.details);
        overrides.set(l.entityId, [...(overrides.get(l.entityId) ?? []), `${d?.step ?? '?'}:${d?.basis ?? '?'}`]);
      }
    }
    for (const l of renewalLogs) {
      const pid = parseDetails(l.details)?.paymentRequestId;
      if (l.userId && typeof pid === 'string' && !makerFromLog.has(pid)) makerFromLog.set(pid, { userId: l.userId, at: l.createdAt });
    }

    const userIds = new Set();
    const rows = [];
    for (const p of payments) {
      const maker = p.requestedById ?? makerFromLog.get(p.id)?.userId ?? null;
      if (!maker) continue;
      const approver = p.approvedById ?? approverFromLog.get(p.id)?.userId ?? null;
      const payer = p.paidById ?? payerFromLog.get(p.id)?.userId ?? null;
      const selfApproved = !!approver && approver === maker;
      const selfPaid = !!payer && payer === maker;
      if (!args.all && !selfApproved && !selfPaid) continue;
      [maker, approver, payer].forEach((u) => u && userIds.add(u));
      rows.push({
        p, maker, approver, payer, selfApproved, selfPaid,
        makerSource: p.requestedById ? 'column' : 'audit-log',
        approvedAt: approverFromLog.get(p.id)?.at ?? null,
        paidAt: payerFromLog.get(p.id)?.at ?? null,
        overrides: (overrides.get(p.id) ?? []).join(' '),
      });
    }

    const users = userIds.size
      ? await prisma.user.findMany({ where: { id: { in: [...userIds] } }, select: { id: true, email: true, role: true } })
      : [];
    const byId = new Map(users.map((u) => [u.id, u]));

    const header = [
      'paymentRequestId', 'title', 'amount', 'status', 'entityType', 'createdAt',
      'makerId', 'makerEmail', 'makerRole', 'makerSource',
      'approverId', 'approverEmail', 'approvedAt', 'payerId', 'payerEmail', 'paidAt',
      'selfApproved', 'selfPaid', 'loggedOverrides',
    ];
    const out = [header.join(',')];
    for (const r of rows) {
      out.push(
        [
          r.p.id, r.p.title, r.p.amount, r.p.status, r.p.entityType, r.p.createdAt,
          r.maker, byId.get(r.maker)?.email, byId.get(r.maker)?.role, r.makerSource,
          r.approver, r.approver ? byId.get(r.approver)?.email : null, r.approvedAt,
          r.payer, r.payer ? byId.get(r.payer)?.email : null, r.paidAt,
          r.selfApproved, r.selfPaid, r.overrides,
        ].map(csvCell).join(','),
      );
    }
    process.stdout.write(`${out.join('\n')}\n`);
    const selfA = rows.filter((r) => r.selfApproved).length;
    const selfP = rows.filter((r) => r.selfPaid).length;
    console.error(
      `Scanned ${payments.length} payment request(s); ${rows.length} row(s) written; self-approved: ${selfA}, self-paid: ${selfP}.`,
    );
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((err) => {
  console.error(`Error: ${err instanceof Error ? err.message : String(err)}`);
  process.exit(1);
});
